import assert from 'node:assert/strict';
import {readFile,writeFile,stat} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {preparedPayload} from '../web/set-payload.mjs';
import {serializeShow} from '../web/show-format.mjs';
const work=process.argv[2];assert(work,'Pass a new scratch directory');
const bpm=Number(process.argv[3]??113);assert(Number.isInteger(bpm)&&bpm>=40&&bpm<=240);
const root=fileURLToPath(new URL('../',import.meta.url));
const studies=JSON.parse(await readFile(join(root,'src/score.json'),'utf8')).studies;
const {instance:{exports:board}}=await WebAssembly.instantiate(await readFile(join(root,'build/board/browser-board.wasm')));
const set=preparedPayload({format:1,songs:[{title:'SAVED RHYTHM',study:'mx',bpm,feel:17}]},studies);
new Uint8Array(board.memory.buffer,board.bench_set_buffer(),set.length).set(set);
assert.equal(board.bench_boot(1),1);board.bench_audio();
const rhythm=new Uint8Array(140),view=new DataView(rhythm.buffer);
rhythm.set([67,55,82,49,32,bpm,17,83,119,76,2,3]);
view.setUint32(16+3*8,0x11111111,true);view.setUint32(20+3*8,0x01000100,true);
let crc=0xffffffff;
for(const b of rhythm.subarray(0,136)) {crc^=b;for(let bit=0;bit<8;++bit)crc=(crc>>>1)^(crc&1?0xedb88320:0);}
view.setUint32(136,(crc^0xffffffff)>>>0,true);
new Uint8Array(board.memory.buffer,board.bench_rhythm_buffer(),140).set(rhythm);
assert.equal(board.bench_rhythm_import(),0);assert.equal(board.bench_show_export(),0);
const songs=new Uint8Array(board.memory.buffer,board.bench_set_buffer(),board.bench_set_size()).slice();
const attachments=new Uint8Array(board.memory.buffer,board.bench_rhythm_slots_buffer(),board.bench_rhythm_slots_size()).slice();
const show=serializeShow(songs,attachments),input=join(work,'show.cpshow'),output=join(work,'show-virtual.bin');
await writeFile(input,JSON.stringify(show));
const run=(i,o)=>spawnSync(process.execPath,[join(root,'tools/board-show-flash.mjs'),i,o],{encoding:'utf8'});
let result=run(input,output);assert.equal(result.status,0,result.stderr);
const flash=await readFile(output);assert.equal(flash.length,1<<20);
assert.equal(flash.subarray(0x90000,0x90004).toString(),'CPS2');
assert.deepEqual(flash.subarray(0x90100,0x90100+1360),Buffer.from(songs));
assert.deepEqual(flash.subarray(0x90100+1360,0x90100+1360+2416),Buffer.from(attachments));
assert.notEqual(run(input,output).status,0);assert.deepEqual(await readFile(output),flash);
const bad=attachments.slice();bad[bad.length-1]=1;
await writeFile(join(work,'invalid.cpshow'),JSON.stringify(serializeShow(songs,bad)));
assert.notEqual(run(join(work,'invalid.cpshow'),join(work,'invalid.bin')).status,0);
await assert.rejects(stat(join(work,'invalid.bin')),e=>e.code==='ENOENT');
console.log(JSON.stringify({nativeValidated:true,refusedOverwrite:true,rejectedInvalidAttachment:true,output}));
